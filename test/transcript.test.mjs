// --- Omitted language ---

test("omitted lang returns the first manual track even when an auto track is listed first", async () => {
  fake = installFakeFetch(transcriptRoutes({
    player: json(playerResponse({ tracks: [track("es", "Spanish (auto-generated)", "asr"), track("en", "English")] })),
  }));
  const r = await callTool(getVideoTranscript, transcriptArgs({}));
  const sc = transcriptOutput.parse(r.structuredContent);
  assert.equal(sc.languageCode, "en");
  assert.equal(sc.isAutoGenerated, false);
  assert.equal(sc.totalSegments, 3);
  assert.match(r.content[0].text, /lang="en", startSegment=2/);
  // same request count as an explicit lang: watch + player + caption track
  assert.equal(fake.calls.length, 3);
});

