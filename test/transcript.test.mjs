// --- Access errors must stay access errors ---

const accessCases = [
  ["watch page 429", { watch: status(429) }, "rate_limited", 429],
  ["watch page 403", { watch: status(403) }, "forbidden", 403],
  ["watch page CAPTCHA", { watch: text(CAPTCHA_PAGE) }, "rate_limited", undefined],
  ["player 429", { player: status(429) }, "rate_limited", 429],
  ["player 403", { player: status(403) }, "forbidden", 403],
  ["bot check (LOGIN_REQUIRED)", { player: json(playerResponse({ status: "LOGIN_REQUIRED", reason: "Sign in to confirm you’re not a bot" })) }, "login_required", undefined],
  ["age check", { player: json(playerResponse({ status: "LOGIN_REQUIRED", reason: "Sign in to confirm your age" })) }, "login_required", undefined],
];

for (const [name, routes, accessKind, httpStatus] of accessCases) {
  test(`${name} → ACCESS_BLOCKED for languages and transcript`, async () => {
    fake = installFakeFetch(transcriptRoutes(routes));
    for (const r of [
      await callTool(getTranscriptLanguages, { video: VIDEO_ID }),
      await callTool(getVideoTranscript, transcriptArgs({ lang: "en" })),
    ]) {
      const e = errorCode(r);
      assert.equal(e.code, "ACCESS_BLOCKED");
      assert.equal(e.upstream.accessKind, accessKind);
      if (httpStatus) assert.equal(e.upstream.httpStatus, httpStatus);
      assert.match(r.content[0].text, /^❌ \[ACCESS_BLOCKED\]/);
      assert.doesNotMatch(r.content[0].text, /removed|deleted|no captions|disabled/i);
    }
    if (name.startsWith("bot check")) {
      const r = await callTool(getTranscriptLanguages, { video: VIDEO_ID });
      assert.equal(errOf(r).upstream.reason, "Sign in to confirm you’re not a bot");
    }
  });
}

