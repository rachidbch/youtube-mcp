// --- Unavailable video, preserving YouTube's reason ---

for (const [st, reason, expectText] of [
  ["ERROR", "This video has been removed by the uploader", /removed by the uploader/],
  ["UNPLAYABLE", "The uploader has not made this video available in your country", /not made this video available/],
  ["LOGIN_REQUIRED", "This video is private", /private/],
]) {
  test(`playability ${st} (${reason}) → VIDEO_UNAVAILABLE with upstream reason`, async () => {
    fake = installFakeFetch(transcriptRoutes({ player: json(playerResponse({ status: st, reason })) }));
    const e = errorCode(await callTool(getTranscriptLanguages, { video: VIDEO_ID }));
    assert.equal(e.code, "VIDEO_UNAVAILABLE");
    assert.equal(e.upstream.playabilityStatus, st);
    assert.equal(e.upstream.reason, reason);
    assert.match(e.message, expectText);
  });
}

