// --- Input validation ---

test("malformed video input is rejected before any request", async () => {
  fake = installFakeFetch([]);
  for (const video of ["not a video", "https://evil.example/watch?v=AAAAAAAAAAA", "https://youtube.com/watch?v=short"]) {
    for (const r of [
      await callTool(getTranscriptLanguages, { video }),
      await callTool(getVideoTranscript, transcriptArgs({ video })),
    ]) {
      assert.equal(errorCode(r).code, "INVALID_INPUT");
    }
  }
  assert.equal(fake.calls.length, 0);
});

test("non-integer pagination arguments are rejected by the input schema", () => {
  assert.throws(() => transcriptArgs({ maxSegments: 1.5 }));
  assert.throws(() => transcriptArgs({ startSegment: -1 }));
});

test("a 429 is not retried automatically", async () => {
  // A single 429 must produce exactly one request per endpoint: no automatic retry.
  fake = installFakeFetch(transcriptRoutes({ player: status(429) }));
  await callTool(getTranscriptLanguages, { video: VIDEO_ID });
  assert.equal(fake.calls.filter((c) => c.url.includes("/player")).length, 1);
  assert.equal(fake.calls.length, 2);
});
