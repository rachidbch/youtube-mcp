import { z } from "zod";
import { config } from "../utils/config.js";
import { errorResult, toYouTubeError, YouTubeError } from "../utils/errors.js";
import { parseVideoId } from "../utils/parse-video-id.js";
import { fetchCaptionTranscript } from "../utils/youtube-api.js";

export const getVideoTranscriptSchema = z.object({
  video: z
    .string()
    .min(1, "Video URL or ID is required")
    .trim()
    .describe("YouTube video URL or video ID"),
  lang: z
    .string()
    .min(2, "Language code must be at least 2 characters (e.g. 'en', 'id')")
    .max(10)
    .trim()
    .optional()
    .describe("Language code for the transcript (e.g., 'en', 'id', 'ja'). Omit to get the first manual track, or the first auto-generated one if there is no manual track. get_transcript_languages lists the codes."),
  maxSegments: z
    .number()
    .int()
    .min(0)
    .default(0)
    .describe(`Maximum number of transcript segments to return. 0 (default) returns as many as the server allows per response (currently ${config.transcriptPageMaxSegments}). Use with startSegment for pagination.`),
  startSegment: z
    .number()
    .int()
    .min(0)
    .default(0)
    .describe("Segment index to start from (0-based). Use nextStartSegment from the previous response to paginate through long transcripts."),
});

const transcriptSegmentSchema = z.object({
  index: z.number().int().min(0),
  offsetSeconds: z.number(),
  durationSeconds: z.number().nullable(),
  timestamp: z.string(),
  text: z.string(),
});

export const getVideoTranscriptOutputSchema = {
  videoId: z.string(),
  languageCode: z.string().nullable().describe("Language of the returned track; the requested code when unavailable; null when none was requested and the video has no captions"),
  available: z.boolean(),
  isAutoGenerated: z.boolean().nullable().optional().describe("Whether the returned track is YouTube's automatic (ASR) captions; null if unknown"),
  totalSegments: z.number().int().min(0),
  startSegment: z.number().int().min(0),
  returnedSegments: z.number().int().min(0),
  hasMore: z.boolean(),
  nextStartSegment: z.number().int().min(0).nullable(),
  plainText: z.string(),
  message: z.string().optional(),
  reason: z.enum(["NO_CAPTIONS", "LANGUAGE_UNAVAILABLE"]).optional().describe("Why available is false"),
  availableLanguages: z.array(z.string()).optional().describe("Language codes that do exist, when reason is LANGUAGE_UNAVAILABLE"),
  segments: z.array(transcriptSegmentSchema),
};

export async function getVideoTranscript(
  args: z.infer<typeof getVideoTranscriptSchema>,
  extra?: { signal?: AbortSignal }
) {
  let videoId: string;
  try {
    videoId = parseVideoId(args.video);
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    return errorResult(new YouTubeError("INVALID_INPUT", `Invalid video: ${msg}`));
  }

  let transcript: Awaited<ReturnType<typeof fetchCaptionTranscript>>;
  try {
    transcript = await fetchCaptionTranscript(videoId, args.lang, extra?.signal);
  } catch (err: unknown) {
    const e = toYouTubeError(err);
    if (e.code === "CAPTIONS_UNAVAILABLE" || e.code === "LANGUAGE_UNAVAILABLE") {
      return notAvailable(videoId, args.lang, e);
    }
    return errorResult(e);
  }

  const segments = transcript.segments;
  const totalSegments = segments.length;
  const pageSize = args.maxSegments > 0
    ? Math.min(args.maxSegments, config.transcriptPageMaxSegments)
    : config.transcriptPageMaxSegments;
  const start = Math.min(args.startSegment, totalSegments);
  const sliced = segments.slice(start, start + pageSize);

  const hasMore = start + sliced.length < totalSegments;
  const nextStart = start + sliced.length;
  const structuredSegments = sliced.map((seg, index) => ({
    index: start + index,
    offsetSeconds: seg.offset,
    durationSeconds: typeof seg.duration === "number" && !isNaN(seg.duration) ? seg.duration : null,
    timestamp: formatTimestamp(seg.offset),
    text: seg.text,
  }));
  const plainText = sliced.map((s) => s.text).join(" ");

  const kind = transcript.isAutoGenerated === null ? "" : transcript.isAutoGenerated ? ", auto-generated" : ", manual";
  const lines: string[] = [
    `📝 Transcript for video ${videoId} [${transcript.languageCode}${kind}] (segments ${sliced.length > 0 ? start + 1 : start}–${start + sliced.length} of ${totalSegments}):\n`,
  ];

  for (const seg of structuredSegments) {
    lines.push(`[${seg.timestamp}] ${seg.text}`);
  }

  if (hasMore) {
    lines.push(`\n⏭️ More transcript available. Fetch next chunk with lang="${transcript.languageCode}", startSegment=${nextStart}${args.maxSegments > 0 ? ` and maxSegments=${args.maxSegments}` : ""}.`);
  }

  lines.push("\n--- Plain text ---\n");
  lines.push(plainText);

  return {
    content: [{ type: "text" as const, text: lines.join("\n") }],
    structuredContent: {
      videoId,
      languageCode: transcript.languageCode,
      available: true,
      isAutoGenerated: transcript.isAutoGenerated,
      totalSegments,
      startSegment: start,
      returnedSegments: structuredSegments.length,
      hasMore,
      nextStartSegment: hasMore ? nextStart : null,
      plainText,
      segments: structuredSegments,
    },
  };
}

/** Captions genuinely absent, or absent in the requested language: a normal result, not an error. */
function notAvailable(videoId: string, lang: string | undefined, e: YouTubeError) {
  const languageMissing = e.code === "LANGUAGE_UNAVAILABLE";
  const availableLanguages = e.upstream.availableLanguages ?? [];
  const message = languageMissing
    ? `No captions in language "${lang}". Available: ${availableLanguages.length > 0 ? availableLanguages.join(", ") : "none"}.`
    : "This video has no captions.";

  return {
    content: [{ type: "text" as const, text: message }],
    structuredContent: {
      videoId,
      languageCode: lang ?? null,
      available: false,
      isAutoGenerated: null,
      totalSegments: 0,
      startSegment: 0,
      returnedSegments: 0,
      hasMore: false,
      nextStartSegment: null,
      plainText: "",
      message,
      reason: languageMissing ? ("LANGUAGE_UNAVAILABLE" as const) : ("NO_CAPTIONS" as const),
      ...(languageMissing && { availableLanguages }),
      segments: [],
    },
  };
}

/** Convert offset in seconds to a human-readable timestamp */
function formatTimestamp(offsetSec: number): string {
  const totalSeconds = Math.floor(offsetSec);
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;

  if (hours > 0) {
    return `${hours}:${minutes.toString().padStart(2, "0")}:${seconds.toString().padStart(2, "0")}`;
  }
  return `${minutes}:${seconds.toString().padStart(2, "0")}`;
}
